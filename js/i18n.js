/* ==================== MOTEUR DE TRADUCTION ==================== */
(function () {
  const originals = new WeakMap();
  const listeners = [];

  function currentLang() {
    return document.documentElement.getAttribute('lang') === 'en' ? 'en' : 'fr';
  }

  function applyLang(lang) {
    const dict = window.I18N.en;
    document.documentElement.setAttribute('lang', lang);

    document.querySelectorAll('[data-i18n]').forEach(el => {
      if (!originals.has(el)) originals.set(el, el.innerHTML);
      const key = el.dataset.i18n;
      el.innerHTML = lang === 'en' && dict[key] ? dict[key] : originals.get(el);
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      if (!el.dataset.frPh) el.dataset.frPh = el.getAttribute('placeholder') || '';
      const key = el.dataset.i18nPlaceholder;
      el.setAttribute('placeholder', lang === 'en' && dict[key] ? dict[key] : el.dataset.frPh);
    });

    // Titre et description de la page
    const meta = document.querySelector('meta[name="description"]');
    if (!document.documentElement.dataset.frTitle) {
      document.documentElement.dataset.frTitle = document.title;
      if (meta) document.documentElement.dataset.frDesc = meta.getAttribute('content');
    }
    if (!document.body.dataset.dynamicTitle) {
      document.title = lang === 'en' ? dict['meta.title'] : document.documentElement.dataset.frTitle;
    }
    if (meta) meta.setAttribute('content', lang === 'en' ? dict['meta.desc'] : document.documentElement.dataset.frDesc);

    document.querySelectorAll('[data-lang-toggle]').forEach(btn => {
      btn.textContent = window.I18N.ui[lang].langBtn;
      btn.setAttribute('aria-label', window.I18N.ui[lang].langLabel);
    });

    listeners.forEach(fn => fn(lang));
  }

  window.i18n = {
    lang: currentLang,
    t: (key) => window.I18N.ui[currentLang()][key] || key,
    pick: (obj) => obj[currentLang()] || obj.fr,
    onChange: (fn) => listeners.push(fn),
    set: (lang) => {
      try { localStorage.setItem('lang', lang); } catch (e) {}
      applyLang(lang);
    },
    init: () => {
      applyLang(currentLang());
      document.querySelectorAll('[data-lang-toggle]').forEach(btn => {
        btn.addEventListener('click', () => window.i18n.set(currentLang() === 'en' ? 'fr' : 'en'));
      });
    }
  };
})();
